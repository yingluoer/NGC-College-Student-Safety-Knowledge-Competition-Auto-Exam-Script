async function fetchQuestion() {
    // 获取题型和题干
    const typeEl = document.querySelector('.type');
    const contentEl = document.querySelector('.content');
    if (!typeEl || !contentEl) {
        console.warn('找不到题型或题干，可能已到末尾或页面未加载');
        return;
    }

    const questionType = typeEl.innerText.replace(/\s+/g, '');
    const questionContent = contentEl.innerText.replace(/^\d+、/, '').trim();

    const answer = answers[questionContent];
    console.log('题型:', questionType);
    console.log('题干:', questionContent);
    console.log('答案:', answer);

    if (!answer) {
        console.warn('answers 里没这道题，跳过选择');
    } else if (questionType === "多选题") {
        // ============ 多选题 ============
        const answerArr = Array.isArray(answer) ? answer : answer.split('');
        const options = Array.from(document.querySelectorAll('.option'));

        for (let i = 0; i < options.length; i++) {
            const option = options[i];
            const labelEl = option.querySelector('.el-checkbox__label');
            const checkboxLabel = option.querySelector('.el-checkbox'); // 外层 label，点它
            if (!labelEl || !checkboxLabel) continue;

            const label = labelEl.innerText.trim();
            const value = label.charAt(0);

            if (answerArr.includes(value)) {
                await new Promise(r => setTimeout(r, i * 100));
                checkboxLabel.click();  // ★ 关键：点外层 label
                console.log('多选点击:', label);
            }
        }
    } else {
        // ============ 单选 ============
        const options = Array.from(document.querySelectorAll('.option'));
        const answerStr = String(answer);

        for (const option of options) {
            const labelEl = option.querySelector('.el-radio__label');
            const radioLabel = option.querySelector('.el-radio'); // 外层 label，点它
            if (!labelEl || !radioLabel) continue;

            const label = labelEl.innerText.trim();
            const value = label.charAt(0);

            if (answerStr === value || answerStr.includes(value)) {
                radioLabel.click();  // ★ 关键：点外层 label
                console.log('单选点击:', label);
                break; 
            }
        }
    }

    // 等 Vue 更新 + 页面渲染
    await new Promise(r => setTimeout(r, 800));

    // 校验是否真的选中
    const checked = document.querySelector('.el-radio__input.is-checked, .el-checkbox__input.is-checked');
    console.log('已选中状态:', !!checked);

    // 找下一题按钮
    const nextBtn = document.querySelector('.next.btn');
    if (!nextBtn) {
        console.log('没有下一题了，结束');
        console.log(questions);
        return;
    }

    if (!checked) {
        console.error('没选中任何选项，停止以避免 nextQuestion 报错');
        return;
    }

    // 记录当前题干，等它变化
    const oldContent = contentEl.innerText;
    nextBtn.click();

    // 等题目真的变了
    const changed = await new Promise(resolve => {
        const start = Date.now();
        const timer = setInterval(() => {
            const cur = document.querySelector('.content')?.innerText || '';
            if (cur && cur !== oldContent) {
                clearInterval(timer);
                resolve(true);
            } else if (Date.now() - start > 5000) {
                clearInterval(timer);
                resolve(false);
            }
        }, 100);
    });

    if (!changed) {
        console.error('题目没变化，nextQuestion 可能失败了，停止');
        return;
    }

    // 递归下一题
    return fetchQuestion();
}

